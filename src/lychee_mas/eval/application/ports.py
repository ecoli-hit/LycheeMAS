class JobManagerPort(Protocol):
    def validate(
        self,
        plan: CompiledPlan,
        mode: str | None = None,
    ) -> dict[str, Any]: ...
    def launch(
        self,
        plan: CompiledPlan,
        mode: str | None = None,
    ) -> dict[str, Any]: ...
    def resume(
        self,
        plan: CompiledPlan,
        mode: str | None = None,
    ) -> dict[str, Any]: ...
    def status(self, launch_dir: Path) -> dict[str, Any]: ...
    def stop(self, launch_dir: Path) -> dict[str, Any]: ...
    def request_drain(self, launch_dir: Path) -> dict[str, Any]: ...
    def launch_utility(
        self,
        *,
        job_id: str,
        command: list[str],
        cwd: Path,
        job_root: Path,
        env: dict[str, str] | None = None,
    ) -> dict[str, Any]: ...
    def progress(self, launch_dir: Path, *, tail: int = 40) -> dict[str, Any]: ...
    def tmux_sessions(self) -> list[dict[str, Any]]: ...


class DeploymentPressureProvider(Protocol):
    def snapshot(self) -> dict[str, Any]: ...
