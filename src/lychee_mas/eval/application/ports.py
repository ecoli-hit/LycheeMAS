"""Structural ports consumed by LycheeMAS Eval application services.

Concrete file-backed registries, process launchers, and pressure monitors implement
these protocols implicitly. Application services depend on these narrow surfaces so
HTTP, CLI, TUI, tests, and future persistence adapters share the same use cases.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol

from ..experiments.compiler import CompiledPlan


class ModelRegistryPort(Protocol):
    def specs(self) -> list[dict[str, Any]]: ...
    def instances(self) -> list[dict[str, Any]]: ...
    def get_spec(self, spec_id: str) -> dict[str, Any]: ...
    def get_instance(self, instance_id: str) -> dict[str, Any]: ...
    def sources(self, spec_id: str, provider: str = "auto") -> list[dict[str, Any]]: ...
    def save_instance(self, value: dict[str, Any]) -> dict[str, Any]: ...
    def delete_instance(self, instance_id: str) -> dict[str, Any]: ...
    def scan_root(self, models_root: str | Path) -> dict[str, Any]: ...


